#pragma once
#include <string>
#include <vector>

#include <glm/glm.hpp>

#include "sage/anim/Skeleton.h"

class Scene;

// ---------------------------------------------------------------------------
// Доступ к костям персонажа — то, на чём стоит ручная анимация скелета.
//
// Проигрывание клипа и ручная поза живут по разные стороны одной границы:
//   • движок сэмплирует клип и считает позу (sage::anim::Animator);
//   • инструмент хранит переопределения локальных TRS (PoseComponent) и отдаёт
//     их движку — тот применяет их поверх клипа.
// Здесь — всё, что нужно обеим сторонам: найти скелет сущности, найти кость по
// имени, прочитать её ТЕКУЩУЮ локальную позу и записать новую.
//
// Ключевое решение: ЧИТАЕМ ВСЕГДА ТО, ЧТО ВИДНО. Если кость переопределена —
// отдаём переопределение; если нет — восстанавливаем локальный TRS из позы,
// которую сейчас насчитал движок (клип, кросс-фейд или дефолт скелета). Поэтому
// «поставить ключ» на кость посреди готовой ходьбы даёт именно ту позу, что в
// кадре, а не прыжок в bind-позу.
//
// Повороты наружу отдаются углами Эйлера в ГРАДУСАХ, в том же порядке
// (X→Y→Z), что и Transform.Rotation движка. Кватернион в редакторе кривых
// бесполезен — интерполировать его покомпонентно нельзя, а показывать нечем;
// углы же аниматор читает и правит руками. Преобразование — ровно обратное
// тому, как движок собирает матрицу из Transform.Rotation, поэтому «повернуть
// кость на 30°» значит то же самое, что «повернуть объект на 30°».
// ---------------------------------------------------------------------------
namespace d3d {

// Что именно правим у кости. Совпадает по смыслу с sage::anim::AnimPath, но
// живёт отдельно: у инструмента это ещё и выбор в интерфейсе.
enum class BoneChannel { Translation, Rotation, Scale };

// Скелет сущности. nullptr — у сущности нет анимированной модели или модель
// ещё не загрузилась (это нормально в первые кадры после открытия проекта).
const sage::anim::Skeleton* SkeletonOf(Scene& scene, int entityId);

// Индекс кости по имени, -1 — нет такой. Имя — устойчивая привязка: индексы
// костей меняются при переэкспорте модели, имена обычно нет.
int FindJoint(const sage::anim::Skeleton& skeleton, const std::string& name);

// Имя кости по индексу (пустое, если индекс вне скелета).
std::string JointName(Scene& scene, int entityId, int joint);

// Текущая локальная поза кости — то, что видно в кадре (см. комментарий выше).
// false — нет сущности, скелета или такой кости.
bool ReadBoneLocal(Scene& scene, int entityId, int joint, glm::vec3& translation,
                   glm::quat& rotation, glm::vec3& scale);

// Читает один канал кости в values (3 числа). Поворот — в градусах.
bool ReadBoneChannel(Scene& scene, int entityId, int joint, BoneChannel channel, float* values);

// Пишет один канал кости в переопределения позы (создавая PoseComponent при
// необходимости) и сразу пересчитывает позу, чтобы правка была видна В ЭТОМ ЖЕ
// кадре. Поворот принимается в градусах.
bool WriteBoneChannel(Scene& scene, int entityId, int joint, BoneChannel channel, const float* values);

// Снимает переопределение канала — кость возвращается под управление клипа.
bool ClearBoneChannel(Scene& scene, int entityId, int joint, BoneChannel channel);

// Глобальная матрица кости В МИРЕ: трансформ сущности × глобаль кости в
// пространстве модели. Это то, на что ставится гизмо и по чему рисуется скелет.
// false — позы ещё нет.
bool BoneWorldMatrix(Scene& scene, int entityId, int joint, glm::mat4& out);

// Обратная операция к BoneWorldMatrix: мировая матрица кости -> её локальный
// TRS относительно родительской кости. Именно этим гизмо превращается в позу.
// false — позы ещё нет.
bool BoneLocalFromWorld(Scene& scene, int entityId, int joint, const glm::mat4& world,
                        glm::vec3& translation, glm::quat& rotation, glm::vec3& scale);

// Отдаёт движку переопределения позы этой сущности (или снимает их, если поза
// пуста) и пересчитывает позу. Зовётся каждый кадр из AnimationDocument::Apply:
// хранилище компонентов может переехать в памяти, и указатель надо обновлять.
void SyncPoseOverride(Scene& scene, int entityId);

// То же для всех персонажей сцены — вызывается там, где обход по одному
// неудобен (после загрузки проекта, отката undo).
void SyncAllPoseOverrides(Scene& scene);

// Убирает всю ручную позу персонажа: он возвращается к чистому клипу.
void ClearPose(Scene& scene, int entityId);

// --- Обратная кинематика ----------------------------------------------------
// Тянет цепочку из chainLength костей, заканчивающуюся костью endJoint, к точке
// targetWorld (в МИРОВЫХ координатах — аниматор указывает точку в сцене, а не в
// пространстве модели). Двухзвенная цепочка решается аналитически, длинная —
// FABRIK; выбор делает сам движок по длине.
//
// poleWorld — куда «смотрит» колено/локоть; nullptr сохраняет плоскость текущей
// позы. Результат ложится в те же переопределения позы, что и ручная правка,
// поэтому его сразу можно заключить ключом.
//
// Возвращает false, если скелета нет или цепочка не набирается; outReached —
// дотянулись ли до цели (цель могла оказаться дальше вытянутой конечности).
bool SolveBoneIK(Scene& scene, int entityId, int endJoint, int chainLength,
                 const glm::vec3& targetWorld, const glm::vec3* poleWorld, float weight,
                 bool& outReached);

// Мировая позиция кости — начальная точка для цели IK: аниматор тянет ручку
// оттуда, где кость сейчас, а не из начала координат.
bool BoneWorldPosition(Scene& scene, int entityId, int joint, glm::vec3& out);

// --- Углы Эйлера ↔ кватернион в конвенции движка (X→Y→Z, градусы) ---
glm::quat QuatFromEulerDegrees(const glm::vec3& degrees);
glm::vec3 EulerDegreesFromQuat(const glm::quat& q);

} // namespace d3d
