#pragma once
#include <string>
#include <vector>

#include <glm/glm.hpp>

class Scene;

// ---------------------------------------------------------------------------
// Ограничения (constraints) — правила, которые доводят объект ПОСЛЕ анимации.
//
// Зачем они вообще нужны. Камера, следящая за героем; рука, держащая меч;
// объект, идущий по траектории, — всё это до сих пор делалось ключами вручную,
// и каждая правка героя означала переделку камеры. Ограничение выражает
// НАМЕРЕНИЕ («смотри на него»), а не его последствия, поэтому переживает любую
// правку того, на что смотрит.
//
// ГДЕ ОНИ ПРИМЕНЯЮТСЯ. В самом конце AnimationDocument::Apply — то есть на
// каждом пути одинаково: во вьюпорте, в Render View, в экспорте ролика и в
// экспорте glTF. Из этого следует приятное: в glTF ограничения ЗАПЕКАЮТСЯ сами
// собой, потому что экспорт снимает уже готовые трансформы. Отдельного «экспорта
// ограничений» не нужно, и чужая программа получает ровно то, что видит автор.
//
// ПОРЯДОК ВЫЧИСЛЕНИЯ. Ограничения цепляются друг за друга: камера смотрит на
// руку, рука привязана к телу, тело идёт по траектории. Считать их в порядке
// создания нельзя — результат зависел бы от того, что человек добавил раньше.
// Поэтому строится порядок по зависимостям (цель считается раньше того, кто на
// неё ссылается), а кольцевые ссылки распознаются и не применяются: «А смотрит
// на Б, Б смотрит на А» — это не ошибка пользователя, которую надо наказать
// зависанием, а обычная опечатка при выборе цели.
// ---------------------------------------------------------------------------
namespace d3d {

enum class ConstraintType {
    None,
    LookAt,   // повернуться лицом к цели
    Parent,   // следовать за трансформом цели
    Path,     // двигаться по траектории из точек-потомков цели
};

const char* ConstraintTypeName(ConstraintType type);

struct ConstraintComponent {
    ConstraintType Type = ConstraintType::None;
    int TargetId = -1;

    // Сила: 0 — выключено, 1 — полностью. Значения между ними смешивают
    // «как было» и «как требует ограничение». Это анимируемое свойство
    // (Property::ConstraintInfluence), и в нём весь смысл плавных включений:
    // камера подхватывает героя за полсекунды, а не прыгает на него.
    float Influence = 1.0f;

    // --- LookAt ---
    // Ось «вверх» в мире. Ею разрешается неоднозначность: направление на цель
    // задаёт только два угла из трёх, третий (крен) остаётся свободным.
    glm::vec3 UpAxis{0.0f, 1.0f, 0.0f};

    // --- Parent ---
    // Сохранять взаимное расположение на момент включения. Без этого объект
    // прыгает в начало координат цели, что почти никогда не нужно.
    bool KeepOffset = true;
    bool OffsetValid = false;    // смещение уже посчитано
    glm::mat4 Offset{1.0f};      // локальная матрица объекта в системе цели

    // --- Path ---
    // Положение на траектории, 0..1. Анимируемое (Property::ConstraintProgress):
    // именно им и «едут» по пути.
    float Progress = 0.0f;
    bool FollowTangent = true;   // разворачивать объект по ходу движения
};

// Применяет все ограничения сцены. Зовётся из AnimationDocument::Apply.
void ApplyConstraints(Scene& scene);

// Точки траектории цели — позиции её ПОТОМКОВ по порядку. Отдельная функция,
// потому что ими же рисуется траектория во вьюпорте.
std::vector<glm::vec3> PathPoints(Scene& scene, int targetId);

// Точка и касательная на траектории при параметре t в [0,1]. false — точек
// меньше двух, пути нет.
bool SamplePath(const std::vector<glm::vec3>& points, float t, glm::vec3& position,
                glm::vec3& tangent);

// Ссылается ли ограничение objectId (прямо или через цепочку) само на себя.
// Нужно интерфейсу: выбор такой цели надо показать красным, а не молча
// проигнорировать.
bool ConstraintCycle(Scene& scene, int objectId);

// Порядок вычисления: цели раньше зависимых. Открыт наружу ради проверок —
// правило неочевидное, и словами в комментарии оно не держится.
std::vector<int> ConstraintOrder(Scene& scene);

} // namespace d3d
