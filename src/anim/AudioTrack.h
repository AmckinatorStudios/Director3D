#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// AudioTrack — звуковая дорожка ролика: файл, его положение на таймлайне и
// огибающая громкости для рисования волны (та самая синяя «пила» внизу
// таймлайна).
//
// Почему свой разбор WAV, а не движковый AudioEngine: движок умеет ЗВУЧАТЬ
// (miniaudio проигрывает файл), но не отдаёт сэмплы наружу — а таймлайну нужна
// именно форма сигнала, чтобы аниматор попадал ключами в удары. Разбор здесь —
// это чтение заголовка и децимация в пики, без всякого DSP; проигрыванием
// по-прежнему занимается движок (AudioEngine::PlayMusic).
//
// Поддерживается несжатый WAV (PCM 8/16/24/32 бит и IEEE float 32) — формат,
// в котором приходит экспорт из любого звукового редактора. Для остальных
// форматов дорожка всё равно создаётся (звук проиграется движком), просто
// вместо волны показывается ровная линия и подпись «нет предпросмотра».
// ---------------------------------------------------------------------------
namespace d3d {

class AudioTrack {
public:
    // Загружает файл: считает огибающую, если формат разобран. Возвращает false
    // только если файла нет — неразобранный формат это не ошибка (см. выше).
    bool Load(const std::string& path);
    void Clear();

    bool Loaded() const { return !m_path.empty(); }
    bool HasWaveform() const { return !m_peaks.empty(); }
    const std::string& Path() const { return m_path; }

    // Длительность звука в секундах (0, если формат не разобран).
    float Length() const { return m_length; }

    // Смещение начала звука на таймлайне (звук может начинаться не с нуля).
    float Offset = 0.0f;
    float Volume = 1.0f;
    bool Muted = false;

    // Огибающая: пара (min, max) на каждый бакет. Размер задаётся при загрузке
    // (kPeakBuckets) — рисование волны не зависит от длины файла и не тормозит
    // на часовой дорожке.
    struct Peak { float Min = 0.0f; float Max = 0.0f; };
    const std::vector<Peak>& Peaks() const { return m_peaks; }

    // Огибающая на участке [t0, t1] таймлайна, приведённая к width бакетам —
    // ровно то, что рисует панель таймлайна при любом зуме. Пустой результат,
    // если участок вне звука.
    std::vector<Peak> Sample(float t0, float t1, int width) const;

    // Сколько бакетов огибающей считается при загрузке.
    static constexpr int kPeakBuckets = 4096;

    // Разбор WAV в моно-сэмплы [-1..1]. Вынесен в статический метод без
    // состояния, чтобы самотест проверял его на сгенерированном буфере, не
    // трогая диск. false — не WAV / неподдерживаемый кодек.
    static bool DecodeWav(const std::vector<unsigned char>& bytes,
                          std::vector<float>& outMono, int& outSampleRate);

private:
    std::string m_path;
    float m_length = 0.0f;
    std::vector<Peak> m_peaks;
};

} // namespace d3d
