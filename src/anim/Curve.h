#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Кривая анимации — последовательность ключей «время → значение» и правило,
// КАК идти между ними. Это самый нижний слой Director 3D: чистая математика,
// ничего не знающая ни о сцене, ни об ImGui, ни об OpenGL. Всё, что рисует
// редактор кривых и что применяется к сцене каждый кадр, считается здесь.
//
// Один Curve хранит ОДНУ скалярную величину (X позиции, интенсивность света,
// FOV). Векторные свойства — это несколько кривых внутри дорожки (см. Track),
// поэтому X/Y/Z можно ключить и сглаживать независимо, как в любом взрослом
// анимационном пакете.
//
// Ключи всегда отсортированы по времени — Evaluate ищет сегмент бинарным
// поиском, а не линейным перебором: у длинной сцены на дорожке легко сотни
// ключей, и поиск идёт КАЖДЫЙ кадр для КАЖДОГО канала.
// ---------------------------------------------------------------------------
namespace d3d {

// Как значение идёт ОТ этого ключа К следующему.
//   Constant — ступенька: держим значение ключа до самого следующего (видимость,
//              смена состояний, «щёлкнул» переключатель);
//   Linear   — прямая (постоянная скорость): механика, конвейеры, развёртки;
//   Smooth   — авто-сглаживание: касательные считаются по соседям
//              (Catmull-Rom), кривая проходит через ключи без изломов. Дефолт —
//              именно то, чего человек ждёт от «просто поставил два ключа»;
//   Bezier   — ручные касательные (InTangent/OutTangent): полный контроль,
//              редактируется мышью в Graph Editor;
//   EaseIn / EaseOut / EaseInOut — готовые кривые разгона/торможения. Это то,
//              что в простом режиме заменяет возню с касательными: «плавно
//              стартовать», «плавно остановиться», «и то и другое».
enum class Interp { Constant, Linear, Smooth, Bezier, EaseIn, EaseOut, EaseInOut };

const char* InterpName(Interp mode);          // человекочитаемое имя для UI
const char* InterpKey(Interp mode);           // короткий ключ для файла проекта
Interp InterpFromKey(const std::string& key); // разбор ключа файла (дефолт — Smooth)

struct Keyframe {
    float Time = 0.0f;
    float Value = 0.0f;
    Interp Mode = Interp::Smooth;

    // Касательные в единицах «значение за секунду» — используются только при
    // Interp::Bezier. InTangent описывает вход В ключ (левая ручка в графе),
    // OutTangent — выход ИЗ ключа (правая ручка).
    float InTangent = 0.0f;
    float OutTangent = 0.0f;
};

class Curve {
public:
    // Ставит ключ. Если ключ на этом времени уже есть (с точностью до
    // kTimeEpsilon) — ПЕРЕЗАПИСЫВАЕТ его значение, а не плодит дубликат:
    // «поставить ключ» на занятом кадре в любом редакторе означает «обновить».
    // Возвращает индекс ключа.
    int SetKey(float time, float value, Interp mode = Interp::Smooth);

    // Удаляет ключ по индексу. false — индекс вне диапазона.
    bool RemoveKey(int index);

    // Двигает ключ во времени и по значению, сохраняя сортировку. Возвращает
    // НОВЫЙ индекс ключа (перетаскивание в графе может перескочить через соседа).
    int MoveKey(int index, float newTime, float newValue);

    // Значение кривой в момент time. Вне диапазона ключей — держится крайнее
    // значение (не экстраполируем: за пределами анимации объект должен стоять,
    // а не улетать). Без ключей возвращает fallback.
    float Evaluate(float time, float fallback = 0.0f) const;

    // Индекс ключа на этом времени или -1. Нужен UI, чтобы показать «на текущем
    // кадре ключ есть» (закрашенный ромб) и переключать его по клику.
    int KeyIndexAt(float time) const;

    // Индекс последнего ключа со временем <= time (-1, если все позже).
    int SegmentIndexAt(float time) const;

    // Касательные, которые РЕАЛЬНО используются при отрисовке/расчёте сегмента
    // (для Smooth они вычисляются, для Bezier берутся из ключа). Graph Editor
    // рисует ручки именно по ним, поэтому картинка совпадает с движением.
    void EffectiveTangents(int index, float& outIn, float& outOut) const;

    // Переводит ключ в Bezier, зафиксировав текущие вычисленные касательные —
    // «схватить ручку» у авто-сглаженного ключа не должно дёргать кривую.
    void ConvertToBezier(int index);

    bool Empty() const { return m_keys.empty(); }
    int Count() const { return (int)m_keys.size(); }
    const std::vector<Keyframe>& Keys() const { return m_keys; }
    std::vector<Keyframe>& KeysMutable() { return m_keys; } // для загрузки проекта
    const Keyframe& At(int i) const { return m_keys[(size_t)i]; }
    Keyframe& AtMutable(int i) { return m_keys[(size_t)i]; }

    void Clear() { m_keys.clear(); }

    // Границы кривой по времени и по значению (для авто-масштаба графа).
    float FirstTime() const { return m_keys.empty() ? 0.0f : m_keys.front().Time; }
    float LastTime() const { return m_keys.empty() ? 0.0f : m_keys.back().Time; }
    void ValueRange(float& outMin, float& outMax) const;

    // Восстанавливает сортировку и схлопывает дубликаты по времени. Вызывается
    // после загрузки проекта: файл мог быть отредактирован руками, а инвариант
    // «ключи отсортированы» держит весь остальной код.
    void Normalize();

    // Совпадение времён с этой точностью считается «тот же кадр». 1e-4 c —
    // мельче, чем полкадра даже при 1000 fps, и грубее ошибки float.
    static constexpr float kTimeEpsilon = 1e-4f;

private:
    std::vector<Keyframe> m_keys; // всегда отсортированы по Time
};

} // namespace d3d
