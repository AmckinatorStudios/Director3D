#pragma once
#include <string>
#include <vector>

#include "anim/AudioTrack.h"
#include "anim/Binding.h"
#include "anim/Curve.h"

class Scene;

// ---------------------------------------------------------------------------
// AnimationDocument — вся анимация проекта: что, когда и как меняется.
//
// Документ ОТДЕЛЁН от сцены. Сцена отвечает на вопрос «что стоит в кадре»
// (её грузит и сохраняет движковый SceneSerializer), документ — «как это
// движется во времени». Отсюда всё остальное:
//   • перемотка = Apply(scene, t): документ пишет в сцену значения на момент t,
//     а не хранит собственную копию мира. Сцена всегда одна и та же;
//   • undo снимает слепок обоих, и они не могут разъехаться;
//   • ту же сцену можно открыть без анимации (или с другой) — это просто сцена.
//
// Три вида дорожек, ровно как на таймлайне:
//   Track     — свойство сущности, разложенное по каналам-кривым (Location X/Y/Z);
//   ClipTrack — блоки скелетных клипов персонажа (Hero_Idle → Hero_Run → …);
//   AudioTrack— звуковая дорожка сцены с волновой формой (см. AudioTrack.h).
//
// Время везде в СЕКУНДАХ (float) — так же, как dt движка. Кадры/таймкод — это
// только представление (см. Playback.h): смена fps не должна двигать анимацию.
// ---------------------------------------------------------------------------
namespace d3d {

// Дорожка одного свойства одной сущности. Каналов 1 или 3 — по PropertyInfo.
struct Track {
    int Id = 0;
    int TargetId = 0;          // id сущности в сцене
    Property Prop = Property::Position;
    // Кость, если дорожка костная (IsBoneProperty), иначе -1. Имя хранится
    // рядом с индексом намеренно: индексы костей меняются при переэкспорте
    // модели, имена — почти никогда, поэтому при загрузке проекта индекс
    // ПЕРЕИЩЕТСЯ по имени, а к сохранённому мы падаем только как к запасному.
    int Joint = -1;
    std::string JointName;
    bool Muted = false;        // не применяется к сцене (но остаётся в проекте)
    bool Locked = false;       // защита от правки ключей мышью
    bool Expanded = true;      // раскрыта ли в таймлайне (состояние UI, сохраняется)
    std::vector<Curve> Channels;

    int ChannelCount() const { return (int)Channels.size(); }
};

// Блок скелетного клипа на таймлайне персонажа — цветной прямоугольник в
// референсе. Клип берётся из загруженной модели (.glb) по индексу.
struct ClipBlock {
    std::string Name;      // подпись на блоке (обычно имя клипа модели)
    int ClipIndex = 0;     // индекс в SkinnedModel::Clips()
    float Start = 0.0f;    // когда блок начинается на таймлайне, сек
    float Duration = 1.0f; // сколько идёт на таймлайне, сек
    float Speed = 1.0f;    // множитель скорости проигрывания клипа
    float BlendIn = 0.25f; // кросс-фейд с предыдущим блоком, сек
    bool Loop = true;      // зациклить клип, если блок длиннее клипа
};

// Дорожка скелетных клипов одной сущности (у неё должен быть AnimatedModelComponent).
struct ClipTrack {
    int Id = 0;
    int TargetId = 0;
    bool Muted = false;
    std::vector<ClipBlock> Blocks; // отсортированы по Start
};

// Именованная метка времени: «начало сцены», «удар», «смена плана».
struct Marker {
    std::string Name;
    float Time = 0.0f;
    unsigned int Color = 0xFF3FC8E8;
};

// Буфер обмена ключей.
//
// Ключ запоминается НЕ по дорожке, а по свойству, подындексу и каналу: только
// так его можно вставить другому объекту. Ссылка на дорожку-источник была бы
// бессмысленной у получателя — у него своя дорожка того же свойства или её ещё
// нет вовсе.
//
// Время хранится ОТНОСИТЕЛЬНО начала копирования. Вставка кладёт ключи от
// текущей головки, сохраняя рисунок: скопировали три ключа за полсекунды —
// вставились три ключа за полсекунды, где бы ни стояла головка.
struct ClipboardKey {
    Property Prop = Property::Position;
    int Joint = -1;
    int Channel = 0;
    float Offset = 0.0f; // от начала копирования, сек
    Keyframe Key;        // значение, режим интерполяции, касательные
};

struct KeyClipboard {
    std::vector<ClipboardKey> Keys;
    bool Empty() const { return Keys.empty(); }
    void Clear() { Keys.clear(); }
    int Count() const { return (int)Keys.size(); }
};

class AnimationDocument {
public:
    // --- Параметры монтажа ---
    float Fps = 24.0f;       // кадров в секунду (таймкод, шаг стрелками, экспорт)
    float Duration = 20.0f;  // длина ролика в секундах
    std::string Name = "My_Animation_Project";

    // --- Содержимое ---
    std::vector<Track> Tracks;
    std::vector<ClipTrack> ClipTracks;
    std::vector<Marker> Markers;
    AudioTrack Audio;

    // --- Дорожки свойств ---------------------------------------------------
    // joint значим только для костных свойств; у остальных он всегда -1, и
    // передавать его не нужно.
    Track* FindTrack(int targetId, Property prop, int joint = -1);
    const Track* FindTrack(int targetId, Property prop, int joint = -1) const;
    Track* TrackById(int id);
    // Возвращает существующую дорожку или создаёт новую с нужным числом каналов.
    Track& EnsureTrack(int targetId, Property prop, int joint = -1);
    void RemoveTrack(int id);
    void RemoveTracksOf(int targetId); // при удалении сущности из сцены
    // Пересаживает костные дорожки на актуальные индексы костей по ИМЕНАМ.
    //
    // Нужно после загрузки проекта: скелет становится известен только когда
    // движок догрузит модель (лениво, через кадр-другой), а индексы костей
    // меняются при любом переэкспорте персонажа. Имя переживает переэкспорт,
    // индекс — нет, поэтому имя главнее.
    //
    // Возвращает число дорожек, которые ещё НЕ удалось привязать (скелета пока
    // нет). Пока результат не ноль, вызывающий повторяет попытку следующим
    // кадром; ноль — можно перестать.
    int RebindBoneTracks(Scene& scene);

    // Костные дорожки одной сущности (для списка костей и подсветки в дереве).
    std::vector<const Track*> BoneTracksOf(int targetId) const;
    // Есть ли у сущности хоть одна костная дорожка — по этому дерево сцены
    // показывает, что персонаж анимируется руками.
    bool HasBoneTracks(int targetId) const;

    // --- Дорожки клипов ----------------------------------------------------
    ClipTrack* FindClipTrack(int targetId);
    ClipTrack& EnsureClipTrack(int targetId);
    void RemoveClipTrack(int id);

    // --- Ключи -------------------------------------------------------------
    // Ставит ключ по ТЕКУЩЕМУ состоянию сущности в сцене (кнопка «Key» и
    // авто-ключ): читает свойство, кладёт значения во все каналы на время time.
    // false — свойство к сущности неприменимо. Создаёт дорожку при необходимости.
    bool KeyFromScene(Scene& scene, int targetId, Property prop, float time, int joint = -1);

    // Ставит ключи на ВСЕ три канала выбранной кости по её текущей позе —
    // «заключить позу». Именно так работает ключевание персонажа: аниматор
    // ставит позу целиком, а не вспоминает, что он трогал поворот, но не
    // перенос. Возвращает, сколько дорожек затронуто.
    int KeyBone(Scene& scene, int targetId, int joint, float time);

    // То же для всего скелета — «заключить всю позу» одной кнопкой. Ключи
    // ставятся только на кости, которые аниматор ТРОГАЛ (есть переопределение)
    // или у которых уже есть дорожка: иначе сотня костей засорила бы проект
    // ключами, которые никто не ставил.
    int KeyPose(Scene& scene, int targetId, float time);

    // Ставит ключи по текущему состоянию сразу для всех дорожек этой сущности
    // (авто-ключ после перетаскивания гизмо трогает и позицию, и поворот, и
    // масштаб — но только там, где дорожка УЖЕ есть, чтобы не засорять проект).
    int KeyExistingTracks(Scene& scene, int targetId, float time);

    // Убирает ключи на этом времени во всех каналах дорожки. Возвращает,
    // сколько убрал.
    int RemoveKeysAt(Track& track, float time);

    // --- Операции над ключами ----------------------------------------------
    // Кладёт в буфер ключи дорожек, попавших во временной диапазон. Диапазон, а
    // не список ссылок: так одна операция обслуживает и «скопировать выделенное
    // рамкой», и «скопировать всё в отрезке».
    //
    // trackIds пуст — берутся все дорожки объекта. Возвращает, сколько взято.
    int CopyKeys(int targetId, const std::vector<int>& trackIds, float from, float to,
                 KeyClipboard& out) const;

    // Вставляет буфер на объект targetId, начиная с времени atTime. Дорожки
    // создаются при необходимости: вставить анимацию на объект, у которого её
    // не было, — обычное дело, ради этого копирование между объектами и нужно.
    //
    // Ключ на занятом времени ПЕРЕЗАПИСЫВАЕТСЯ (как и при обычном ключевании).
    // Возвращает, сколько ключей легло.
    int PasteKeys(int targetId, const KeyClipboard& clip, float atTime);

    // Растягивает или сжимает ключи объекта во времени вокруг pivot.
    // factor > 1 — растянуть, 0 < factor < 1 — сжать.
    //
    // Нужно, когда движение получилось правильным, но слишком быстрым: без
    // этого пришлось бы двигать каждый ключ руками, теряя рисунок.
    // Возвращает, сколько ключей переехало.
    int ScaleKeyTimes(int targetId, const std::vector<int>& trackIds, float from, float to,
                      float pivot, float factor);

    // «Запекает» кривые дорожки в ключи по кадрам: значение сэмплируется на
    // каждом кадре диапазона и ставится ключом со ступенчатой... нет, с
    // линейной интерполяцией — форма уже задана самими ключами.
    //
    // Зачем: после запекания кривая перестаёт быть формулой и становится
    // данными. Это нужно, чтобы отдать анимацию наружу (формат-получатель может
    // не знать про Безье и разгоны) и чтобы править отдельные кадры руками, не
    // ломая соседние. Операция НЕОБРАТИМАЯ по смыслу — сглаженная кривая после
    // неё уже не восстановится, поэтому вызывающий обязан спросить.
    int BakeTrack(Track& track, float from, float to, float fps);

    // Есть ли ключ на этом времени хотя бы в одном канале дорожки.
    bool HasKeyAt(const Track& track, float time) const;

    // Ближайшее время ключа строго до/после указанного, среди ВСЕХ дорожек
    // (кнопки «предыдущий/следующий ключ» на транспорте). Возвращает false,
    // если ключей в эту сторону нет.
    bool PrevKeyTime(float from, float& out) const;
    bool NextKeyTime(float from, float& out) const;

    // --- Применение к сцене -------------------------------------------------
    // Пишет в сцену состояние на момент time: все не-заглушенные дорожки
    // свойств + активные блоки клипов. Это ЕДИНСТВЕННЫЙ путь, которым документ
    // влияет на мир, — и в интерактивной перемотке, и в проигрывании, и в
    // покадровом рендере секвенции.
    //
    // seeking различает два режима для СКЕЛЕТНЫХ клипов (кривые от него не
    // зависят — они и так считаются от абсолютного времени):
    //   false — непрерывное проигрывание: клип ведётся движком (Animator::Update
    //           тикает сам), работает кросс-фейд между блоками;
    //   true  — головку перетащили/перепрыгнули/рендерим кадр секвенции: поза
    //           ставится точно на нужное время через Animator::Seek, без
    //           зависимости от того, какой кадр показывали до этого.
    void Apply(Scene& scene, float time, bool seeking) const;

    // Полная длительность контента (самый поздний ключ/блок/конец звука) —
    // «подогнать длину ролика под содержимое».
    float ContentEnd() const;

    // Сбрасывает всё содержимое, сохраняя параметры монтажа.
    void ClearContent();

    // Есть ли вообще что применять (пустой документ не трогает сцену).
    bool Empty() const { return Tracks.empty() && ClipTracks.empty(); }

    int NextId() const { return m_nextId; }
    void SetNextId(int id) { m_nextId = id; }
    int TakeId() { return m_nextId++; }

private:
    int m_nextId = 1;
};

} // namespace d3d
