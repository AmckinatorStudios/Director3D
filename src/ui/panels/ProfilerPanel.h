#pragma once

namespace d3d {

class DirectorHost;

// ---------------------------------------------------------------------------
// Панель профилировщика: сколько миллисекунд занял каждый проход кадра.
//
// ЗАЧЕМ ОНА В ПРОГРАММЕ, А НЕ ТОЛЬКО В ДВИЖКЕ. Пока «стало медленно» —
// ощущение, а не число, чинить нечего: правки идут наугад, и половина из них
// делает хуже. Панель отвечает на единственный вопрос, с которого начинается
// оптимизация: где именно уходит время.
//
// ЧИТАТЬ ЕЁ НАДО ПРАВИЛЬНО. CPU и GPU идут ПАРАЛЛЕЛЬНО: пока видеокарта рисует
// прошлый кадр, процессор собирает следующий. Поэтому узкое место — максимум из
// двух столбцов, а не сумма, и «CPU 4 мс + GPU 9 мс» означает кадр за 9 мс, а
// не за 13.
//
// Профилировщик выключен, пока панель закрыта: метки времени GPU не бесплатны,
// и платить за них, когда на них никто не смотрит, незачем.
// ---------------------------------------------------------------------------
class ProfilerPanel {
public:
    void Draw(DirectorHost& host);

    bool& Visible() { return m_visible; }

private:
    bool m_visible = false;
    bool m_wasVisible = false;
    bool m_average = true; // покадровые значения скачут; по умолчанию — сглаженные
};

} // namespace d3d
