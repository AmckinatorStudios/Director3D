#pragma once
#include <string>

namespace d3d {

class DirectorHost;

// ---------------------------------------------------------------------------
// Окружение сцены: небо, солнце, фоновая засветка, туман.
//
// Это НЕ свойства объекта, поэтому им не место в инспекторе — в сцене нет
// сущности «мир», и вешать окружение на случайно выбранный объект было бы
// враньём. Отдельная панель совпадает и с движком: Scene::Lighting — часть
// сцены, а не компонент сущности.
//
// Небо в двух режимах: процедурный градиент (два цвета, без единого файла) и
// кубическая текстура из каталога с гранями px/nx/py/ny/pz/nz.
// ---------------------------------------------------------------------------
class WorldPanel {
public:
    void Draw(DirectorHost& host);

private:
    // Буфер поля ввода каталога неба. Отдельный от самой настройки: путь
    // применяется по кнопке, а не на каждый набранный символ — иначе движок
    // пытался бы собрать cubemap из каждого промежуточного огрызка пути.
    char m_skyDir[512] = "";
    // Для какой сцены буфер заполнен: при загрузке проекта его надо перечитать.
    bool m_skyDirLoaded = false;
    std::string m_lastError;
};

} // namespace d3d
