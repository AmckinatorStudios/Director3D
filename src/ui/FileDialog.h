#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Системные диалоги выбора файлов.
//
// Почему через СИСТЕМНУЮ УТИЛИТУ, а не через библиотеку вроде nativefiledialog.
// Такая библиотека на Linux тянет заголовки GTK или Qt, то есть превращает
// «собрать инструмент» в «сначала поставь пакеты разработки рабочего стола».
// На сборочной машине их обычно нет, и вместо удобного диалога получаешь
// упавшую сборку — цена, несопоставимая с выгодой.
//
// Здесь диалог открывает штатная утилита окружения: zenity или kdialog на
// Linux, osascript на macOS, PowerShell на Windows. Зависимостей сборки ноль,
// диалог — настоящий системный, а если ничего из этого нет, Available()
// честно отвечает «нет», и интерфейс оставляет ввод пути строкой. Тот же приём
// уже используется для ffmpeg: внешний инструмент, работающий если он есть.
//
// Вызов БЛОКИРУЮЩИЙ: пока пользователь выбирает файл, окно инструмента не
// перерисовывается. Для модального диалога это ожидаемо и совпадает с
// поведением любого другого приложения.
// ---------------------------------------------------------------------------
namespace d3d::filedialog {

// Один фильтр расширений. Patterns — шаблоны через пробел: "*.d3dproj",
// "*.glb *.gltf *.obj".
struct Filter {
    std::string Name;
    std::string Patterns;
};

// Есть ли в системе чем открыть диалог. false — интерфейс должен оставить
// ручной ввод пути и не показывать кнопку «Обзор».
bool Available();

// Имя найденной утилиты (для строки состояния и отчёта о проблемах). Пусто,
// если ничего не нашлось.
const std::string& Backend();

// Выбор существующего файла. false — пользователь отменил или диалог не
// открылся; out в этом случае не трогается.
bool OpenFile(const std::string& title, const std::vector<Filter>& filters,
              const std::string& startDir, std::string& out);

// Выбор имени для сохранения. suggestedName — имя, предложенное по умолчанию.
// Подтверждение перезаписи показывает сама системная утилита.
bool SaveFile(const std::string& title, const std::vector<Filter>& filters,
              const std::string& startDir, const std::string& suggestedName, std::string& out);

// Выбор каталога (каталог рендера, каталог граней кубической карты).
bool PickFolder(const std::string& title, const std::string& startDir, std::string& out);

// Экранирование строки для командной строки оболочки.
//
// Открыто наружу РАДИ ПРОВЕРОК, и это оправдано: в команду попадают пути от
// пользователя и из файла проекта, а ошибка здесь — не косметика, а
// возможность выполнить произвольную команду через имя файла. Такое обязано
// проверяться тестом, а не глазами.
std::string QuoteForShell(const std::string& value);

} // namespace d3d::filedialog
