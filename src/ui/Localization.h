#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Локализация интерфейса.
//
// Ключ перевода — САМА РУССКАЯ СТРОКА, а не выдуманный идентификатор.
//
// Это осознанный выбор, и он важнее, чем кажется. С идентификаторами
// (`T(STR_OPEN_PROJECT)`) исходный код перестаёт показывать, что написано в
// интерфейсе: чтобы понять, какая надпись у кнопки, надо идти в таблицу. При
// пяти сотнях строк это превращает чтение панелей в постоянные прыжки. Со
// строкой-ключом надпись видна прямо на месте, а перевод — отдельная таблица
// рядом. Так устроен gettext, и по той же причине.
//
// Плата: правка русского текста рвёт связь с переводом молча. Поэтому есть
// проверка полноты (см. MissingKeys) — она находит строки, которым перевода
// нет, и самотест на ней падает.
//
// Словарь лежит ДАННЫМИ (assets/i18n/en.json), а не в коде: пополнять его
// можно без пересборки, а отсутствие файла не ломает программу — интерфейс
// просто остаётся русским.
// ---------------------------------------------------------------------------
namespace d3d::i18n {

enum class Language { Russian, English };

// Загружает словарь из каталога (ожидается <dir>/en.json). false — файла нет
// или он битый; интерфейс в этом случае остаётся русским, и это не авария.
bool LoadDictionary(const std::string& directory);

void SetLanguage(Language language);
Language CurrentLanguage();
// Короткий код для файла настроек: "ru" / "en".
const char* LanguageCode();
bool SetLanguageByCode(const std::string& code);

// Выбранный язык переживает перезапуск: файл director3d_lang.txt рядом с
// настройками окон. Отдельный крошечный файл, а не поле в файле проекта —
// язык интерфейса принадлежит человеку, а не ролику, и переезжать вместе с
// проектом на чужую машину он не должен.
void LoadPreference();
void SavePreference();

// Перевод строки. Возвращает саму строку, если язык русский или перевода нет.
//
// Возвращаемый указатель живёт до конца работы программы: ImGui хранит
// переданные ему строки до конца кадра, и отдавать временный буфер нельзя.
const char* Translate(const char* russian);

// Сколько пар в словаре (для строки состояния и проверок).
int DictionarySize();

// Русские строки, которых нет в словаре. Пусто — покрытие полное.
// Заполняется теми строками, которые РЕАЛЬНО запрашивались через Translate,
// поэтому список отражает то, что видел пользователь, а не весь исходник.
const std::vector<std::string>& MissingKeys();

} // namespace d3d::i18n

// Короткое имя для использования в панелях: T("Открыть проект").
// Свободная функция, а не макрос: макрос с таким именем почти наверняка
// столкнулся бы с чужим кодом, а инлайн-функция уважает пространства имён.
inline const char* T(const char* russian) { return d3d::i18n::Translate(russian); }
