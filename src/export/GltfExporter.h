#pragma once
#include <string>

#include "anim/AnimationDocument.h"

class Scene;

// ---------------------------------------------------------------------------
// Экспорт анимации в glTF 2.0 (.glb).
//
// Зачем. До этого готовая анимация жила только в .d3dproj — формате, который
// понимает один инструмент. Отдать движение в игру, в Blender или в браузер
// было нечем. glTF читают все, поэтому именно он.
//
// ЧТО ВЫГРУЖАЕТСЯ
//   • иерархия объектов сцены с анимированными переносом, поворотом и
//     масштабом;
//   • камеры — как настоящие glTF-камеры (перспектива с yfov);
//   • скелеты персонажей — узлами костей с их локальными TRS, включая ручную
//     позу поверх клипа.
//
// ЧЕГО НЕТ, И ПОЧЕМУ ЭТО НЕ НЕДОДЕЛКА, А ГРАНИЦА ФОРМАТА
//   • Геометрия. Файл содержит анимацию и скелет, но не меши: модели пришли из
//     чужих .glb, и перекладывать их вершины через инструмент анимации значило
//     бы ухудшать их копию. Принимающая сторона берёт СВОЮ модель и накладывает
//     это движение.
//   • Угол обзора, яркость света, параметры пост-обработки. В ядре glTF
//     анимируются только translation/rotation/scale/weights узлов; канала для
//     fov или интенсивности там нет. Такие дорожки остаются в .d3dproj.
//   • Веса блендшейпов. Канал weights в glTF есть, но он адресует морф-цели
//     МЕША, а меша мы не пишем — адресовать было бы нечего.
//
// КАК СЧИТАЮТСЯ ЗНАЧЕНИЯ
// Кадры снимаются ТЕМ ЖЕ AnimationDocument::Apply, которым рисуется кадр в
// рендере. Отдельного вычислителя кривых для экспорта нет намеренно: два пути
// расчёта неизбежно разъезжаются, и расхождение выглядело бы как «в файле
// анимация не такая, как в программе».
//
// Кривые ЗАПЕКАЮТСЯ по кадрам с линейной интерполяцией между ними, а не
// переводятся в CUBICSPLINE. Причина в том, что наши касательные Безье и
// касательные glTF — не одно и то же, и перевод между ними приблизителен;
// запечённая кривая совпадает с проигранной точно на каждом кадре, то есть
// ровно там, где её видно.
// ---------------------------------------------------------------------------
namespace d3d::gltf {

struct Options {
    // 0 — взять частоту кадров документа.
    float Fps = 0.0f;
    bool IncludeCameras = true;
    bool IncludeLights = true;   // как пустые узлы: своих ламп в ядре glTF нет
    bool IncludeSkeletons = true;
};

struct Result {
    int Nodes = 0;
    int Channels = 0;   // сколько дорожек анимации ушло в файл
    int Samples = 0;    // кадров на дорожку
    int Bytes = 0;
};

// Пишет .glb по пути path. false — err содержит причину.
//
// ВНИМАНИЕ: функция гоняет сцену по времени (Apply на каждом кадре) и оставляет
// её на последнем снятом моменте. Вызывающий обязан вернуть сцену на головку
// сам — здесь неоткуда узнать, где она была.
bool Export(const std::string& path, Scene& scene, const AnimationDocument& doc,
            const Options& options, Result& result, std::string& err);

} // namespace d3d::gltf
